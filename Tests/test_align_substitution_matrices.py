class TestBasics(unittest.TestCase):
    def test_basics_vector(self):
        """Test basic vector operations."""
        counts = substitution_matrices.Array("XYZ")
        assert str(counts) == """\
X 0.0
Y 0.0
Z 0.0
"""
        assert counts.alphabet == "XYZ"
        counts["X"] = -9
        counts[2] = 5.5
        assert str(counts) == """\
X -9.0
Y  0.0
Z  5.5
"""
        assert counts[0] == pytest.approx(-9, abs=5e-8)
        with pytest.raises(IndexError):
            counts["U"]
        with pytest.raises(IndexError):
            counts["V"] = 3.0
        with pytest.raises(IndexError):
            counts[8]

    def test_basics_matrix(self):
        """Test basic matrix operations."""
        counts = substitution_matrices.Array("XYZ", dims=2)
        assert str(counts) == """\
    X   Y   Z
X 0.0 0.0 0.0
Y 0.0 0.0 0.0
Z 0.0 0.0 0.0
"""
        counts["X", "Z"] = 12.0
        counts[2, 1] = 3.0
        counts["Y", 0] = -2.0
        counts[0, "Y"] = 5.0
        assert str(counts) == """\
     X   Y    Z
X  0.0 5.0 12.0
Y -2.0 0.0  0.0
Z  0.0 3.0  0.0
"""
        with pytest.raises(IndexError):
            counts["U", 1]
        with pytest.raises(IndexError):
            counts["X", 5]
        assert str(counts["Y"]) == """\
X -2.0
Y  0.0
Z  0.0
"""
        assert str(counts[:, "Z"]) == """\
X 12.0
Y  0.0
Z  0.0
"""

    def test_read_write(self):
        """Test reading and writing substitution matrices."""
        path = os.path.join("Align", "hg38.chrom.sizes")
        sizes = substitution_matrices.read(path, np.int64)
        # Note that sum(sizes) below is larger than 2147483647, and won't
        # fit in an int on a 32-bits machine.
        assert len(sizes) == 455
        assert sizes["chr1"] == 248956422
        assert sizes["chr2"] == 242193529
        assert sizes["chr3"] == 198295559
        assert sizes["chr4"] == 190214555
        assert sizes["chr5"] == 181538259
        assert sum(sizes) == 3209286105
        text = str(sizes)
        lines = text.split("\n")
        assert lines[0] == "chr1 248956422"
        assert lines[1] == "chr2 242193529"
        assert lines[2] == "chr3 198295559"
        assert lines[3] == "chr4 190214555"
        assert lines[4] == "chr5 181538259"

    def test_nucleotide_freq(self):
        """Test nucleotide frequency calculations."""
        counts = Counter()
        path = os.path.join("Align", "ecoli.fa")
        records = SeqIO.parse(path, "fasta")
        for record in records:
            for nucleotide in record.seq:
                counts[nucleotide] += 1
        letters = sorted(counts.keys())
        assert letters == sorted(nucleotide_alphabet)
        path = os.path.join("Align", "ecoli.txt")
        frequencies = substitution_matrices.read(path)
        assert frequencies.alphabet == nucleotide_alphabet
        assert frequencies.shape == (len(nucleotide_alphabet),)
        for letter in letters:
            assert frequencies[letter] == pytest.approx(counts[letter], abs=5e-8)
        with open(path) as handle:
            text = handle.read()
        assert frequencies.format("%d") == text
        total = sum(frequencies)
        assert total == pytest.approx(sum(counts.values()), abs=5e-8)
        frequencies /= total
        assert frequencies.alphabet == nucleotide_alphabet
        assert frequencies["A"] == pytest.approx(0.251621271076524, abs=5e-8)
        assert frequencies["C"] == pytest.approx(0.228274967574578, abs=5e-8)
